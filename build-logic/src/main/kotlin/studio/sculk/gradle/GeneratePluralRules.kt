package studio.sculk.gradle

import groovy.json.JsonSlurper
import org.gradle.api.DefaultTask
import org.gradle.api.GradleException
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates `CldrPluralRules`, the CLDR cardinal plural rules of every locale in [plurals]
 * (`cldr-core/supplemental/plurals.json`) as Kotlin, for whole-number counts.
 *
 * For a whole number every operand but `n` and `i` is zero, so each relation on `v`, `w`, `f`, `t`,
 * `c` or `e` is decided here and only comparisons on the count remain in the generated code.
 */
@CacheableTask
abstract class GeneratePluralRules : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val plurals: RegularFileProperty

    @get:Input
    abstract val packageName: Property<String>

    @get:OutputDirectory
    abstract val output: DirectoryProperty

    @TaskAction
    fun generate() {
        val root = (JsonSlurper().parse(plurals.get().asFile) as Map<*, *>)["supplemental"] as Map<*, *>
        val cldr = ((root["version"] as Map<*, *>)["_cldrVersion"] as String)
        val locales = (root["plurals-type-cardinal"] as Map<*, *>).entries.associate { (locale, rules) ->
            locale as String to ruleSet(locale, rules as Map<*, *>)
        }
        // Many locales share a rule set; each distinct one becomes a single function.
        val distinct = locales.values.distinct()
        val byRuleSet = locales.entries.groupBy({ it.value }, { it.key })
        val pkg = packageName.get()
        val source = buildString {
            appendLine("// Generated by GeneratePluralRules from CLDR $cldr plurals.json (Unicode-3.0). Do not edit.")
            appendLine("package $pkg")
            appendLine()
            appendLine("/** CLDR $cldr cardinal plural rules for whole numbers, by CLDR locale id (`fr`, `pt-PT`). */")
            appendLine("internal object CldrPluralRules {")
            appendLine("    const val CLDR_VERSION: String = \"$cldr\"")
            appendLine()
            appendLine("    /** The category of the non-negative whole number [n] in [locale], or null when CLDR has no rules for it. */")
            appendLine("    fun category(locale: String, n: Long): PluralCategory? = when (locale) {")
            distinct.forEachIndexed { index, ruleSet ->
                val ids = byRuleSet.getValue(ruleSet).sorted().joinToString(", ") { "\"$it\"" }
                appendLine("        $ids -> rules$index(n)")
            }
            appendLine("        else -> null")
            appendLine("    }")
            distinct.forEachIndexed { index, ruleSet ->
                // A condition that always holds ends the rule set and becomes its fallback.
                val fallback = ruleSet.lastOrNull()?.takeIf { it.second == "true" }?.first ?: "OTHER"
                val conditional = ruleSet.filter { it.second != "true" }
                appendLine()
                if (conditional.isEmpty()) {
                    appendLine("    @Suppress(\"UNUSED_PARAMETER\")")
                    appendLine("    private fun rules$index(n: Long): PluralCategory = PluralCategory.$fallback")
                } else {
                    appendLine("    private fun rules$index(n: Long): PluralCategory = when {")
                    conditional.forEach { (category, condition) -> appendLine("        $condition -> PluralCategory.$category") }
                    appendLine("        else -> PluralCategory.$fallback")
                    appendLine("    }")
                }
            }
            appendLine("}")
        }
        val dir = output.get().asFile.resolve(pkg.replace('.', '/')).apply { mkdirs() }
        dir.resolve("CldrPluralRules.kt").writeText(source)
    }

    /** The categories of one locale before `other`, in CLDR order, with conditions that can still be true. */
    private fun ruleSet(locale: String, rules: Map<*, *>): List<Pair<String, String>> {
        val result = mutableListOf<Pair<String, String>>()
        for (category in CATEGORIES) {
            val text = rules["pluralRule-count-${category.lowercase()}"] as? String ?: continue
            val condition = try {
                parse(text.substringBefore('@').trim())
            } catch (failure: IllegalArgumentException) {
                throw GradleException("CLDR rule for $locale $category is not understood: '$text' (${failure.message})")
            }
            when (condition) {
                Condition.False -> continue
                // Always true for whole numbers: every later category is unreachable.
                Condition.True -> {
                    result += category to "true"
                    return result
                }
                is Condition.Code -> result += category to condition.kotlin
            }
        }
        return result
    }

    private sealed interface Condition {
        data object True : Condition

        data object False : Condition

        data class Code(val kotlin: String) : Condition
    }

    private fun parse(rule: String): Condition {
        if (rule.isEmpty()) return Condition.False
        val alternatives = rule.split(" or ").map { and -> all(and.split(" and ").map { relation(it.trim()) }) }
        if (alternatives.any { it == Condition.True }) return Condition.True
        val codes = alternatives.filterIsInstance<Condition.Code>()
        return when (codes.size) {
            0 -> Condition.False
            1 -> codes.single()
            else -> Condition.Code(codes.joinToString(" || ") { "(${it.kotlin})" })
        }
    }

    private fun all(relations: List<Condition>): Condition {
        if (relations.any { it == Condition.False }) return Condition.False
        val codes = relations.filterIsInstance<Condition.Code>()
        return if (codes.isEmpty()) Condition.True else Condition.Code(codes.joinToString(" && ") { it.kotlin })
    }

    private fun relation(text: String): Condition {
        val match = RELATION.matchEntire(text) ?: throw IllegalArgumentException("relation '$text'")
        val (operand, modulus, operator, list) = match.destructured
        val negated = operator == "!="
        val ranges = list.split(',').map { item ->
            val bounds = item.trim().split("..")
            require(bounds.size in 1..2) { "range '$item'" }
            bounds.first().toLong()..bounds.last().toLong()
        }
        if (operand !in COUNT_OPERANDS) {
            // v, w, f, t, c and e are zero for a whole number, and zero modulo anything is zero.
            return if (ranges.any { 0L in it } != negated) Condition.True else Condition.False
        }
        val subject = if (modulus.isEmpty()) "n" else "n % ${modulus}L"
        val tests = ranges.map { range ->
            if (range.first == range.last) {
                if (negated) "$subject != ${range.first}L" else "$subject == ${range.first}L"
            } else {
                if (negated) "$subject !in ${range.first}L..${range.last}L" else "$subject in ${range.first}L..${range.last}L"
            }
        }
        return Condition.Code(
            when {
                tests.size == 1 -> tests.single()
                negated -> tests.joinToString(" && ")
                else -> "(" + tests.joinToString(" || ") + ")"
            },
        )
    }

    private companion object {
        val CATEGORIES = listOf("ZERO", "ONE", "TWO", "FEW", "MANY")
        val COUNT_OPERANDS = setOf("n", "i")
        val RELATION = Regex("""([nivwftce])(?:\s*%\s*(\d+))?\s*(!=|=)\s*([\d.,\s]+)""")
    }
}
