// Maven Central first: the plugin portal serves Kotlin artifacts only through a redirect to it,
// and a failed redirect on a CI runner broke resolution of the kotlin-dsl plugin's dependencies.
pluginManagement {
    repositories {
        mavenCentral()
        gradlePluginPortal()
    }
}

dependencyResolutionManagement {
    repositories {
        mavenCentral()
        gradlePluginPortal()
    }
    versionCatalogs {
        create("libs") {
            from(files("../gradle/libs.versions.toml"))
        }
    }
}

rootProject.name = "build-logic"
